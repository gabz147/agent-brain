"""Write docs/agents/<id>.md and docs/agents/README.md from automation/adapters/*.json.

  python tools/gen_agent_docs.py           regenerate
  python tools/gen_agent_docs.py --check   exit 1 if the committed pages are stale

The manifests are the source of truth; edit them, never the generated pages.
"""
import argparse
from pathlib import Path
import sys

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO / "automation"))
import vault_adapters  # noqa: E402

OUT = REPO / "docs/agents"
HEADER = "<!-- Generated by tools/gen_agent_docs.py from automation/adapters/{id}.json; edit the manifest instead. -->\n"
TIER = {True: "hooks: the brief, write checks and checkpoint reminder arrive by hook",
        False: "instructions only: the agent runs `vaultctl.py session-brief` once and checkpoints when it hands back"}
DIALECT = {"exit2-stdout-async": "exit 2 with the request on stdout, woken asynchronously",
           "json-decision-block": "JSON `{\"decision\": \"block\", \"reason\": ...}` on exit 0, which continues the turn",
           "json-decision-deny": "JSON decision on exit 0", "json-followup": "JSON follow-up message",
           "exit1-stderr": "exit 1 with the request on stderr", "none": "no Stop request"}


def page(adapter):
    a, hooks = adapter, adapter.get("hooks")
    lines = [HEADER.format(id=a["id"]), f"# {a['display']}", "",
             f"Setup id: `{a['id']}` (`python install.py --client {a['id']}`). Tier: {TIER[bool(hooks)]}.", "",
             "| What | Where |", "|---|---|"]
    path = a["instructions"]["path"]
    lines.append(f"| Instructions | `{path}` ({a['instructions']['strategy']}) |" if path else f"| Instructions | none global ({a['instructions']['strategy']}) |")
    lines.append("| Skills | " + ", ".join(f"`{d}`" for d in a["skills"]) + " (installed once, in the first one not already shared) |")
    if a.get("legacy_skills"):
        lines.append("| Legacy skills | " + ", ".join(f"`{d}`" for d in a["legacy_skills"]) + " (refreshed in place when present, never created) |")
    if hooks:
        lines.append(f"| Hooks | `{hooks['path']}`, scripts in `{hooks['scripts']}`; Stop answers with {DIALECT[hooks['gate_output']]} |")
    else:
        lines.append("| Hooks | none wired yet |")
    lines.append(f"| Checkpoint | " + ("transcript (`--source " + a["id"] + " --session <id> --transcript <path>`)" if a["transcript_adapter"]
                                     else "attested (`--source " + a["id"] + " --model <runtime id>` with the summary flags)") + " |")
    lines.append(f"| Detected by | " + ", ".join([f"`{d}`" for d in a["detect"]["dirs"]] + [f"`{b}` on PATH" for b in a["detect"]["binaries"]]
                                                 + [f"`${e}`" for e in a["detect"]["env"]]) + " |")
    lines.append(f"| Verified version | {a['verified_version'] or 'not yet fixture-verified on a named release'} |")
    if a.get("min_version"):
        lines.append(f"| Minimum version | {a['min_version']} |")
    lines += ["", "The line this agent gets after the shared rules:", "", "> " + a["instructions"]["tail"], "", a["notes"], ""]
    if a.get("docs"):
        lines += [f"Vendor documentation: {a['docs']}", ""]
    return "\n".join(lines)


def index(adapters):
    lines = ["<!-- Generated by tools/gen_agent_docs.py from automation/adapters/; edit the manifests instead. -->", "# Agents", "",
             "Each agent is one manifest in `automation/adapters/`; a new agent is a JSON file plus fixtures, not code.", "",
             "| Agent | Setup id | Tier | Instructions |", "|---|---|---|---|"]
    for a in adapters.values():
        tier = "hooks" if a.get("hooks") else "instructions only"
        lines.append(f"| [{a['display']}]({a['id']}.md) | `{a['id']}` | {tier} | `{a['instructions']['path'] or 'project only'}` |")
    return "\n".join(lines) + "\n"


def rendered():
    adapters = vault_adapters.load(REPO / "automation/adapters")
    files = {OUT / f"{name}.md": page(a) for name, a in adapters.items()}
    files[OUT / "README.md"] = index(adapters)
    return files


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    files = rendered()
    stale = [p for p, text in files.items() if not p.is_file() or p.read_text(encoding="utf-8") != text]
    extra = [p for p in OUT.glob("*.md") if p not in files] if OUT.is_dir() else []
    if args.check:
        for path in stale + extra:
            print(f"stale: {path.relative_to(REPO).as_posix()}")
        return 1 if stale or extra else 0
    OUT.mkdir(parents=True, exist_ok=True)
    for path, text in files.items():
        path.write_bytes(text.encode("utf-8"))
    for path in extra:
        path.unlink()
    print(f"wrote {len(files)} pages")
    return 0


if __name__ == "__main__":
    sys.exit(main())
